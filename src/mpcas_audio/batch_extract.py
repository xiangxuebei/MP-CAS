#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Batch CLI for speech and audio-language feature extraction.

This wrapper reuses the modular audio pipeline, but reads the WAV
manifest generated by mpcas_tasks.audio_extraction so subject/task/phase fields
match the Samsung data layout used by the classifier pipeline.
"""

from __future__ import annotations

import argparse
import gc
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional

import numpy as np
import pandas as pd


ID_ORDER = [
    "subject",
    "folder_subject",
    "subject_code",
    "device_id",
    "version",
    "timestamp",
    "task",
    "phase",
    "wav_path",
]

AUDIO_EXTENSIONS = {".wav", ".m4a", ".mp3", ".aac", ".flac", ".ogg", ".mav"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Extract full speech/audio/text features for Samsung audio tasks.")
    parser.add_argument("--dataset-dir", type=Path, required=True, help="Root containing extracted audio.wav files.")
    parser.add_argument("--result-csv", type=Path, required=True, help="Output CSV path.")
    parser.add_argument("--manifest-csv", type=Path, default=None, help="Optional audio_wav_manifest.csv path.")
    parser.add_argument("--subjects", nargs="*", default=None)
    parser.add_argument("--tasks", nargs="*", default=None)
    parser.add_argument("--versions", nargs="*", default=None)
    parser.add_argument("--phases", nargs="*", default=None)
    parser.add_argument("--log-interval", type=int, default=10)
    parser.add_argument(
        "--retry-failed",
        action="store_true",
        help="Reuse existing result CSV and only process missing or failed rows.",
    )
    parser.add_argument("--worker-row-json", type=Path, default=None, help=argparse.SUPPRESS)
    parser.add_argument("--worker-output-json", type=Path, default=None, help=argparse.SUPPRESS)
    return parser.parse_args()


def as_filter(values: Optional[Iterable[str]]) -> Optional[set]:
    if not values:
        return None
    out = {str(value).strip() for value in values if str(value).strip()}
    return out or None


def default_manifest_path(dataset_dir: Path) -> Path:
    return dataset_dir.parent / "audio_features" / "audio_wav_manifest.csv"


def resolve_wav_path(value: object, dataset_dir: Path, manifest: Path) -> str:
    text = str(value).strip()
    if not text:
        return ""
    path = Path(text)
    if path.is_absolute():
        return str(path)

    candidates = [
        Path.cwd() / path,
        manifest.parent / path,
        dataset_dir.parent.parent / path,
        dataset_dir / path,
    ]
    for candidate in candidates:
        if candidate.exists():
            return str(candidate.resolve())
    return str((Path.cwd() / path).resolve())


def rows_from_manifest(dataset_dir: Path, manifest_csv: Optional[Path]) -> pd.DataFrame:
    manifest = manifest_csv or default_manifest_path(dataset_dir)
    if manifest.exists():
        df = pd.read_csv(manifest, low_memory=False)
        if "wav_path" not in df.columns:
            raise ValueError(f"manifest does not contain wav_path: {manifest}")
        if "audio_extract_ok" in df.columns:
            df = df[pd.to_numeric(df["audio_extract_ok"], errors="coerce").fillna(0).astype(int) == 1]
        df["wav_path"] = df["wav_path"].map(lambda value: resolve_wav_path(value, dataset_dir, manifest))
        return df.copy()

    rows: List[Dict[str, object]] = []
    for path in sorted(dataset_dir.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in AUDIO_EXTENSIONS:
            continue
        rel = path.relative_to(dataset_dir)
        parts = rel.parts
        phase = parts[-2] if len(parts) >= 2 else ""
        task = parts[-3] if len(parts) >= 3 else ""
        subject = parts[-4] if len(parts) >= 4 else (parts[0] if parts else "")
        rows.append(
            {
                "subject": subject,
                "folder_subject": subject,
                "subject_code": subject,
                "device_id": "",
                "version": "",
                "timestamp": "",
                "task": task,
                "phase": phase,
                "wav_path": str(path),
                "audio_extract_ok": 1,
            }
        )
    return pd.DataFrame(rows, columns=[*ID_ORDER, "audio_extract_ok"])


def filter_rows(df: pd.DataFrame, args: argparse.Namespace) -> pd.DataFrame:
    subjects = as_filter(args.subjects)
    tasks = as_filter(args.tasks)
    versions = as_filter(args.versions)
    phases = as_filter(args.phases)
    out = df.copy()
    if "wav_path" not in out.columns:
        out["wav_path"] = ""
    if subjects and "subject" in out.columns:
        out = out[out["subject"].astype(str).isin(subjects)]
    if tasks and "task" in out.columns:
        out = out[out["task"].astype(str).isin(tasks)]
    if versions and "version" in out.columns:
        out = out[out["version"].astype(str).isin(versions)]
    if phases and "phase" in out.columns:
        out = out[out["phase"].astype(str).isin(phases)]
    out["wav_path"] = out["wav_path"].astype(str)
    out = out[out["wav_path"].map(lambda value: Path(value).exists())]
    return out.reset_index(drop=True)


def import_engine(dataset_dir: Path, result_csv: Path):
    os.environ["MPCAS_AUDIO_DATASET_DIR"] = str(dataset_dir)
    os.environ["MPCAS_AUDIO_RESULT_CSV"] = str(result_csv)
    from mpcas_audio import pipeline as engine

    engine.DATASET_DIR = str(dataset_dir)
    engine.RESULT_CSV_PATH = str(result_csv)
    engine.RESULT_DIR = str(result_csv.parent)
    return engine


def normalize_result(result: Dict[str, object], row: pd.Series) -> Dict[str, object]:
    out = dict(result)
    for key in ID_ORDER:
        if key in row.index:
            out[key] = row.get(key)
    out["wav_path"] = row.get("wav_path")
    return json_safe(out)


def json_safe(value):
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, list):
        return [json_safe(v) for v in value]
    if isinstance(value, tuple):
        return [json_safe(v) for v in value]
    if isinstance(value, np.ndarray):
        return json_safe(value.tolist())
    if isinstance(value, np.generic):
        value = value.item()
    if isinstance(value, float) and (np.isnan(value) or np.isinf(value)):
        return None
    try:
        if pd.isna(value):
            return None
    except Exception:
        pass
    return value


def make_error_result(row: pd.Series, message: str) -> Dict[str, object]:
    out = {key: row.get(key, "") for key in ID_ORDER if key in row.index}
    out["wav_path"] = row.get("wav_path", "")
    out["文件名"] = row.get("wav_path", "")
    out["错误信息"] = message
    return out


def row_key(row: pd.Series) -> tuple:
    subject = str(row.get("subject", "")).strip()
    task = str(row.get("task", "")).strip()
    phase = str(row.get("phase", "")).strip()
    wav_path = str(row.get("wav_path", "")).strip()
    if wav_path:
        try:
            wav_path = str(Path(wav_path).resolve())
        except Exception:
            pass
    return subject, task, phase, wav_path


def error_columns(df: pd.DataFrame) -> List[str]:
    names = []
    for col in df.columns:
        text = str(col)
        if text in {"错误信息", "閿欒淇℃伅"} or "错误信息" in text or "錯誤信息" in text or "閿欒淇℃伅" in text:
            names.append(col)
    return names


def is_failed_row(row: pd.Series) -> bool:
    for col in error_columns(pd.DataFrame(columns=row.index)):
        value = row.get(col)
        if pd.isna(value):
            continue
        text = str(value).strip()
        if text and text.lower() != "nan":
            return True
    # Retry rows with an explicit ASR failure marker.
    failure_markers = (
        "语音识别完全失败",
        "����ʶ����ȫʧ��",
        "torchcodec is required",
        "dll load failed",
    )
    for value in row.tolist():
        if pd.isna(value):
            continue
        text = str(value).strip().lower()
        if any(marker.lower() in text for marker in failure_markers):
            return True
    return False


def load_existing_successes(result_csv: Path) -> Dict[tuple, Dict[str, object]]:
    if not result_csv.exists():
        return {}
    existing = pd.read_csv(result_csv, low_memory=False)
    if existing.empty:
        return {}
    if "wav_path" not in existing.columns:
        existing["wav_path"] = ""
    successes: Dict[tuple, Dict[str, object]] = {}
    failed = 0
    for _, row in existing.iterrows():
        key = row_key(row)
        if is_failed_row(row):
            failed += 1
            continue
        successes[key] = row.to_dict()
    print(
        f"[AUDIO FULL] retry mode loaded existing rows={len(existing)} "
        f"success={len(successes)} failed={failed}",
        flush=True,
    )
    return successes


def write_results(results: List[Dict[str, object]], result_csv: Path) -> None:
    result_csv.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(results)
    id_cols = [col for col in ID_ORDER if col in df.columns]
    other_cols = [col for col in df.columns if col not in id_cols]
    df = df[id_cols + other_cols]
    df.to_csv(result_csv, index=False, encoding="utf-8-sig")


def release_memory() -> None:
    gc.collect()
    try:
        import torch  # type: ignore

        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    except Exception:
        pass


def run_worker_row(args: argparse.Namespace) -> None:
    dataset_dir = args.dataset_dir.resolve()
    result_csv = args.result_csv.resolve()
    row_data = json.loads(args.worker_row_json.read_text(encoding="utf-8"))
    row = pd.Series(row_data)
    engine = import_engine(dataset_dir, result_csv)
    result = engine.extract_audio_features(str(row.get("wav_path", "")))
    payload = normalize_result(result, row)
    args.worker_output_json.parent.mkdir(parents=True, exist_ok=True)
    args.worker_output_json.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")


def process_row_isolated(row: pd.Series, args: argparse.Namespace, index: int) -> Dict[str, object]:
    tmp_dir = args.result_csv.resolve().parent / "_retry_workers"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    row_json = tmp_dir / f"row_{index:05d}.json"
    out_json = tmp_dir / f"out_{index:05d}.json"
    row_json.write_text(json.dumps(json_safe(row.to_dict()), ensure_ascii=False), encoding="utf-8")
    if out_json.exists():
        out_json.unlink()

    cmd = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--dataset-dir",
        str(args.dataset_dir.resolve()),
        "--result-csv",
        str(args.result_csv.resolve()),
        "--worker-row-json",
        str(row_json.resolve()),
        "--worker-output-json",
        str(out_json.resolve()),
    ]
    proc = subprocess.run(cmd, cwd=str(Path(__file__).resolve().parent.parent))
    if proc.returncode != 0:
        return make_error_result(row, f"worker failed: returncode={proc.returncode}")
    if not out_json.exists():
        return make_error_result(row, "worker failed: no output json")
    try:
        return json.loads(out_json.read_text(encoding="utf-8"))
    except Exception as exc:
        return make_error_result(row, f"worker failed: invalid output json: {exc}")


def main() -> None:
    args = parse_args()
    if args.worker_row_json and args.worker_output_json:
        run_worker_row(args)
        return

    dataset_dir = args.dataset_dir.resolve()
    result_csv = args.result_csv.resolve()
    rows = filter_rows(rows_from_manifest(dataset_dir, args.manifest_csv), args)
    result_csv.parent.mkdir(parents=True, exist_ok=True)

    if rows.empty:
        pd.DataFrame(columns=["subject", "task", "phase"]).to_csv(result_csv, index=False, encoding="utf-8-sig")
        print(f"[AUDIO FULL] no wav rows matched filters; wrote empty csv={result_csv}", flush=True)
        return

    existing_successes = load_existing_successes(result_csv) if args.retry_failed else {}
    if existing_successes:
        rows = rows[~rows.apply(lambda row: row_key(row) in existing_successes, axis=1)].reset_index(drop=True)
        print(f"[AUDIO FULL] retry mode rows to process={len(rows)}", flush=True)

    engine = None if args.retry_failed else import_engine(dataset_dir, result_csv)
    results: List[Dict[str, object]] = list(existing_successes.values())
    total = len(rows)
    if total == 0:
        write_results(results, result_csv)
        print(f"[AUDIO FULL] no failed/missing rows to retry; kept {len(results)} rows in {result_csv}", flush=True)
        return
    for index, (_, row) in enumerate(rows.iterrows(), start=1):
        wav_path = str(row["wav_path"])
        if index == 1 or index == total or index % max(1, args.log_interval) == 0:
            print(
                f"[PROGRESS] audio-full {index}/{total} "
                f"{row.get('subject', '')}-{row.get('task', '')}-{row.get('phase', '')}",
                flush=True,
            )
        if args.retry_failed:
            result = process_row_isolated(row, args, index)
        else:
            assert engine is not None
            result = engine.extract_audio_features(wav_path)
        results.append(normalize_result(result, row))
        write_results(results, result_csv)
        release_memory()

    print(f"[AUDIO FULL] saved {len(results)} rows to {result_csv}", flush=True)
    final_table = pd.read_csv(result_csv, low_memory=False)
    failed_rows = int(sum(is_failed_row(row) for _, row in final_table.iterrows()))
    if failed_rows:
        raise RuntimeError(
            f"Audio extraction finished with {failed_rows} retryable failure rows; "
            "the pipeline will not accept this CSV as complete."
        )


if __name__ == "__main__":
    main()
